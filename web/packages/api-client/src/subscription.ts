/**
 * Types for subscriptions, plans and revenue (Phase 6).
 *
 * <p>Mirrors the backend records field for field, including the fields whose whole purpose is to
 * stop the client guessing: `materialised` on an entitlement (a limit from a paid plan versus the
 * free baseline reads differently to an owner), `upgradeTo` on a denial, and the
 * `*Display` strings beside every minor-unit amount.
 *
 * <p><b>Every money figure arrives twice.</b> `mrrMinor` is for arithmetic and `mrrDisplay` is for
 * rendering, because two formatters for one number is how a dashboard ends up showing a total that
 * does not match the sum of its rows.
 */

// ---------------------------------------------------------------- plans

export type BillingPeriod = 'NONE' | 'MONTHLY' | 'ANNUAL';

/** One feature a plan can grant. The list comes from the server, not from here. */
export interface PlanEntitlement {
  feature: string;
  enabled: boolean;
  /** The cap for a countable feature. Null means uncapped. */
  limit: number | null;
}

export interface Plan {
  id: string;
  code: string;
  name: string;
  description: string | null;
  billingPeriod: BillingPeriod;
  priceMinor: number;
  /** Server-formatted, e.g. "Rs. 2,000.00 / month". */
  priceDisplay: string;
  durationDays: number | null;
  isActive: boolean;
  sortOrder: number;
  /** Prose, already humanised by the server: "Up to 500 products". */
  grants: string[];
}

/** The admin's view of a plan, which also carries what it grants and who holds it. */
export interface PlanDetail extends Plan {
  /** What this plan contributes to MRR, so an admin can check the dashboard's arithmetic. */
  monthlyEquivalentMinor: number;
  entitlements: PlanEntitlement[];
  activeSubscribers: number;
}

// ---------------------------------------------------------------- the shop's subscription

export interface FeatureGrant {
  /** The persisted key, e.g. "max_products". Not display text — see `label` on the plan. */
  key: string;
  enabled: boolean;
  limit: number | null;
  /**
   * True when this came from a paid plan rather than the free baseline.
   *
   * <p>Reported because it is the difference between "your plan says 500" and "you get 25 because
   * you have no plan", and an owner reading a limit needs to know which they are looking at.
   */
  materialised: boolean;
}

export interface CurrentPlan {
  subscriptionId: string;
  planCode: string;
  planName: string;
  status: string;
  startedAt: string | null;
  expiresAt: string | null;
  daysRemaining: number;
  /** True once cancelled: still active, but will lapse at expiry. */
  willNotRenew: boolean;
  /** Null once cancelled — nothing left to renew. */
  upgradeToCode: string | null;
}

export interface SubscriptionHistoryEntry {
  subscriptionId: string;
  planCode: string;
  planName: string;
  status: string;
  startedAt: string | null;
  expiresAt: string | null;
  cancelledAt: string | null;
  /** What the plan costs. Present on every row so a pending one can be paid after a reload. */
  amountMinor: number;
  amountDisplay: string;
  /**
   * The transfer reference, or null once there is nothing left to pay.
   *
   * <p>Carried on the history row rather than only in the request response, because otherwise the
   * payment step lives in browser memory: a shop that requested a plan and reloaded would come back
   * to "Awaiting payment" with no amount to send and no reference to quote.
   */
  reference: string | null;
}

/** The whole subscription state, in one response. The page's only GET. */
export interface MySubscription {
  shopId: string;
  history: SubscriptionHistoryEntry[];
  /** Null when the shop has never subscribed — which is the free tier, not an error. */
  current: CurrentPlan | null;
  features: FeatureGrant[];
  /**
   * True when the shop still pays commission.
   *
   * <p>Read from the server rather than inferred from the entitlements, because this is the flag
   * the order-accept path will actually use.
   */
  paysCommission: boolean;
  commissionPlan: 'FREE' | 'SUBSCRIBED';
}

/** What to do next after requesting a plan. */
export interface RequestResult {
  subscriptionId: string;
  planCode: string;
  planName: string;
  amountMinor: number;
  amountDisplay: string;
  billingPeriod: BillingPeriod;
  durationDays: number | null;
  /** The reference the bank transfer must carry, generated by the server. */
  reference: string;
  instructions: string;
  nextStep: string;
}

// ---------------------------------------------------------------- revenue

export interface RevenueMonth {
  month: string;
  mrrMinor: number;
  mrrDisplay: string;
  subscribers: number;
}

/**
 * The admin revenue dashboard.
 *
 * <p>Each ratio's name states its denominator, because a ratio without one means something
 * different on every screen it appears on.
 */
export interface RevenueSummary {
  asOf: string;
  /** Stated rather than implied: "since the start of the current month, except MRR". */
  window: string;

  mrrDisplay: string;
  mrrMinor: number;
  paidSubscribers: number;
  commissionFreeShops: number;
  totalShops: number;
  tradingShops: number;

  /** What the ledger debited, net of reversals. Cash that moved. */
  commissionRealisedDisplay: string;
  commissionRealisedMinor: number;
  /** What orders did *not* charge because the shop was subscribed. Revenue forgone. */
  commissionWaivedDisplay: string;
  commissionWaivedMinor: number;
  commissionReversedDisplay: string;
  commissionReversedMinor: number;
  ordersAccepted: number;

  /** Bank transfers in — subscriptions included, because buying one *is* a transfer in. */
  topUpsDisplay: string;
  topUpsMinor: number;
  subscriptionChargesDisplay: string;
  subscriptionChargesMinor: number;

  subscriptionArpuDisplay: string;
  subscriptionArpuMinor: number;
  platformPerTradingShopDisplay: string;
  platformPerTradingShopMinor: number;
  commissionPerSubscriberDisplay: string;
  commissionPerSubscriberMinor: number;
  commissionFromFreeShopsDisplay: string;

  /** Subscriptions earned per rupee of commission waived. Null when nothing was waived. */
  waiverCoverage: string | null;

  trend: RevenueMonth[];
}

// ---------------------------------------------------------------- refusals

/**
 * A refused operation, as the server describes it.
 *
 * <p>The shape of the problem body, kept in one place because a bare 403 is a wall and this is the
 * difference between a wall and an upsell. See `readEntitlementDenial`.
 */
export interface EntitlementDenial {
  feature: string;
  /**
   * The plan to buy, or null when no plan on sale grants this.
   *
   * <p>Null is meaningful: the UI must not offer an upgrade button that leads to a pricing page
   * where nothing can be bought.
   */
  upgradeTo: string | null;
  limit: number | null;
  currentCount: number | null;
  adding: number | null;
  message: string;
}
